import test from "node:test";
import assert from "node:assert/strict";
import { GET, POST } from "../src/app/referrals/route";
import { GET as detail } from "../src/app/referrals/[id]/route";
import { GET as verification } from "../src/app/referrals/[id]/verification/route";
import { GET as commitment, PUT as create } from "../src/app/demo/commitments/[id]/route";
import { POST as spend } from "../src/app/demo/commitments/[id]/spend/route";
import { POST as login, DELETE as logout } from "../src/app/demo/session/route";
import { demoReferrals } from "@edgecare/shared-types/fixtures";
import { validSession } from "../src/server/auth";

const request = (path = "/referrals", method = "GET", body?: unknown, headers?: HeadersInit) => new Request(`http://localhost${path}`, { method, ...(body === undefined ? {} : { body: JSON.stringify(body) }), headers });
const context = (id: string) => ({ params: Promise.resolve({ id }) });

test("routes enforce private projections, malformed input and complete single-use lifecycle", async () => {
  process.env.DEMO_MODE = "true"; process.env.CHAIN = "mock"; process.env.LLM = "ondevice";
  process.env.EDGECARE_DB_PATH = ":memory:";
  const record = { ...demoReferrals[0]!, referral_id: "11111111-1111-4111-8111-111111111111" };
  const post = (body: unknown) => POST(request("/referrals", "POST", body));
  assert.equal((await post(record)).status, 201);
  assert.equal((await post(record)).status, 200);
  assert.equal((await post({ ...record, language: "fi" })).status, 409);
  for (const patch of [{ status: "spent" }, { patient_name: "Forbidden" }, { signature: [] }, { passcode: "1234" }]) assert.equal((await post({ ...record, ...patch })).status, 400);
  const malformed = new Request("http://localhost/referrals", { method: "POST", body: "{" });
  assert.equal((await POST(malformed)).status, 400);
  assert.equal((await POST(new Request("http://localhost/referrals", { method: "POST", body: "x".repeat(128 * 1024 + 1) }))).status, 400);
  const list = await GET(request());
  assert.equal(list.headers.get("Cache-Control"), "no-store");
  const payload = await list.json();
  for (const item of payload.referrals) for (const key of ["salt", "signature_template_encrypted", "triage_detail_encrypted", "commitment_hash", "source", "kiosk_id"]) assert.equal(key in item, false, key);
  const envelope = await verification(request(), context(record.referral_id));
  assert.equal((await envelope.json()).signature_template_encrypted, record.signature_template_encrypted);
  assert.equal((await detail(request(), context("22222222-2222-4222-8222-222222222222"))).status, 404);
  assert.equal((await detail(request(), context("missing"))).status, 400);
  const ctx = context(record.referral_id);
  assert.equal((await commitment(request(), ctx)).status, 404);
  const hashBody = { commitment_hash: record.commitment_hash };
  assert.equal((await create(request("/demo", "PUT", { ...hashBody, passcode: "1234" }), ctx)).status, 400);
  assert.equal((await create(request("/demo", "PUT", { commitment_hash: "f".repeat(64) }), ctx)).status, 409);
  assert.equal((await create(request("/demo", "PUT", hashBody), ctx)).status, 200);
  assert.equal((await create(request("/demo", "PUT", hashBody), ctx)).status, 200);
  assert.equal((await spend(request("/demo", "POST", { commitment_hash: "f".repeat(64) }), ctx)).status, 409);
  const op = { ...hashBody, operation_id: "33333333-3333-4333-8333-333333333333" };
  const results = await Promise.all([spend(request("/demo", "POST", op), ctx), spend(request("/demo", "POST", { ...hashBody, operation_id: "44444444-4444-4444-8444-444444444444" }), ctx)]);
  assert.deepEqual(results.map(response => response.status).sort(), [200, 409]);
  const settled = await results[0]!.json();
  assert.equal(settled.spent, true);
  assert.deepEqual(Object.keys(settled).sort(), ["commitment_hash", "created_slot", "spent", "spent_slot"]);
  assert.equal((await spend(request("/demo", "POST", op), ctx)).status, 200);
  assert.equal((await spend(request("/demo", "POST", hashBody), ctx)).status, 409);
  assert.equal((await create(request("/demo", "PUT", hashBody), ctx)).status, 200);
  const reconciled = await (await detail(request(), ctx)).json();
  assert.equal(reconciled.status, "spent");
  assert.equal(reconciled.status_history.at(-1).status, "spent");
  assert.equal((await spend(request("/demo", "POST", hashBody), context("55555555-5555-4555-8555-555555555555"))).status, 404);
});

test("browser sessions, role tokens and production guard fail closed", async () => {
  const browser = { "sec-fetch-site": "same-origin" };
  assert.equal((await GET(request("/referrals", "GET", undefined, browser))).status, 401);
  assert.equal((await verification(request("/referrals", "GET", undefined, browser), context(demoReferrals[0]!.referral_id))).status, 401);
  assert.equal((await login(request("/demo/session", "POST", undefined, { origin: "https://attacker.example" }))).status, 403);
  assert.equal((await login(request("/demo/session", "POST", undefined, { host: "127.0.0.1:4317", origin: "http://127.0.0.1:4317" }))).status, 200);
  assert.equal((await login(request("/demo/session", "POST", undefined, { host: "clinic.example", origin: "http://clinic.example" }))).status, 401);
  assert.equal((await GET(request("/referrals", "GET", undefined, { host: "clinic.example" }))).status, 401);
  assert.equal((await login(request("/demo/session", "POST", undefined, { host: "localhost@attacker.example", origin: "http://attacker.example" }))).status, 403);
  assert.equal((await login(request("/demo/session", "POST", undefined, { host: "127.0.0.1:4317", origin: "http://localhost" }))).status, 403);
  const session = await login(request("/demo/session", "POST", undefined, { origin: "http://localhost" }));
  assert.equal(session.status, 200);
  const cookie = session.headers.get("set-cookie")!;
  assert.ok(cookie.includes("HttpOnly") && cookie.includes("SameSite=Strict"));
  assert.equal((await GET(request("/referrals", "GET", undefined, { ...browser, cookie }))).status, 200);
  const raw = cookie.split(";")[0]!.split("=")[1]!;
  assert.equal(validSession(raw), true);
  assert.equal(validSession(`${raw}changed`), false);
  assert.equal(validSession("1.a.b"), false);
  assert.equal((await logout(request("/demo/session", "DELETE"))).headers.get("set-cookie")?.includes("Max-Age=0"), true);
  process.env.EDGECARE_CLINICIAN_TOKEN = "test-clinician-token";
  process.env.EDGECARE_ISSUER_TOKEN = "test-issuer-token";
  try {
    assert.equal((await GET(request())).status, 401);
    assert.equal((await login(request("/demo/session", "POST"))).status, 401);
    assert.equal((await login(request("/demo/session", "POST", undefined, { authorization: "Bearer test-clinician-token" }))).status, 200);
    assert.equal((await login(request("/demo/session", "POST", undefined, { authorization: "Bearer tést-clinician-token" }))).status, 401);
    assert.equal((await GET(request("/referrals", "GET", undefined, { authorization: "Bearer test-issuer-token" }))).status, 401);
    assert.equal((await GET(request("/referrals", "GET", undefined, { authorization: "Bearer test-clinician-token" }))).status, 200);
    assert.equal((await create(request("/demo", "PUT", { commitment_hash: "a".repeat(64) }, { authorization: "Bearer test-clinician-token" }), context("66666666-6666-4666-8666-666666666666"))).status, 401);
  } finally { delete process.env.EDGECARE_CLINICIAN_TOKEN; delete process.env.EDGECARE_ISSUER_TOKEN; }
  process.env.DEMO_MODE = "false";
  assert.equal((await GET(request())).status, 503);
  assert.equal((await login(request("/demo/session", "POST"))).status, 503);
  process.env.DEMO_MODE = "true";
});
